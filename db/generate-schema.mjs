#!/usr/bin/env node
/**
 * Generates the PostgreSQL schema from the desktop app's REAL schema.
 *
 *   node db/generate-schema.mjs            # write db/schema/001_tables.sql + 002_indexes.sql
 *   node db/generate-schema.mjs --stdout   # print instead
 *
 * WHY GENERATED, NOT HAND-WRITTEN
 * -------------------------------
 * 60 tables transcribed by hand is 60 chances to mistype a column name, a
 * default or a nullability — and every one of those is a defect that the verify
 * scripts would surface only indirectly, as a confusing failure somewhere else.
 * Deriving it from `electron/database.js` means the PostgreSQL schema cannot
 * drift from the schema the app actually builds, and the translation rules are
 * stated once, here, where they can be reviewed.
 *
 * The emitted .sql files ARE the schema of record — commit them, review them in
 * diffs. This generator exists so they are reproducible, not so they are
 * ephemeral.
 *
 * HOW THE SOURCE SHAPE IS OBTAINED
 * --------------------------------
 * A fresh install runs createTables(), then the alterStatements loop, then a
 * series of migrate* functions. The final shape is all of it, so this builds a
 * real sql.js database the same way and introspects the result. The migrate*
 * functions are data moves rather than structure, with one exception noted
 * below.
 *
 * TRANSLATION RULES (docs/DECISIONS.md)
 * -------------------------------------
 *   REAL                          -> double precision   D4: NEVER numeric.
 *                                    node-postgres returns numeric as a STRING
 *                                    and the app does plain JS arithmetic.
 *   DATE                          -> text               D5: 'YYYY-MM-DD',
 *                                    compared lexicographically. A real date
 *                                    type changes timezone semantics.
 *   DATETIME                      -> text               same, with a default
 *                                    matching SQLite's CURRENT_TIMESTAMP
 *                                    ('YYYY-MM-DD HH:MM:SS', UTC).
 *   INTEGER                       -> bigint             SQLite INTEGER is 64-bit.
 *   INTEGER PRIMARY KEY AUTOINCR. -> bigint GENERATED BY DEFAULT AS IDENTITY
 *                                    BY DEFAULT, not ALWAYS: the importer must
 *                                    be able to write explicit ids.
 *   FOREIGN KEY                   -> DROPPED            D6: declared but never
 *                                    enforced; the app depends on orphan rows
 *                                    and manual delete ordering.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const REF = join(ROOT, 'Talha Farm');
const require = createRequire(import.meta.url);

const DB_SRC = readFileSync(join(REF, 'electron', 'database.js'), 'utf8');

function extractFn(src, name, kw) {
  const start = src.indexOf(`${kw}${name}(`);
  if (start < 0) throw new Error(`${name} not found in database.js`);
  let i = src.indexOf('(', start);
  let depth = 0;
  for (; i < src.length; i++) {
    if (src[i] === '(') depth++;
    else if (src[i] === ')') {
      depth--;
      if (depth === 0) { i++; break; }
    }
  }
  depth = 0;
  for (i = src.indexOf('{', i); i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}') {
      depth--;
      if (depth === 0) break;
    }
  }
  return src.slice(start, i + 1);
}

const createTables = eval('(' + extractFn(DB_SRC, 'createTables', 'function ') + ')');

// The alterStatements array lives inside initializeDatabase(). Lift it as text.
const alterStatements = (() => {
  const start = DB_SRC.indexOf('const alterStatements = [');
  if (start < 0) throw new Error('alterStatements not found');
  const end = DB_SRC.indexOf('\n  ]', start);
  return eval(DB_SRC.slice(start, end + 4) + '; alterStatements');
})();

// The one migration that changes STRUCTURE rather than data: it rebuilds
// `vaccinations` so batch_id is nullable. Applying it keeps the generated shape
// honest. See docs/LANDMINES.md line 106 — this rebuild has destroyed data
// before, and must become a one-time numbered migration, never a launch-time one.
const migrateVaccinations = eval(
  '(' + extractFn(DB_SRC, 'migrateVaccinationsNullableBatchId', 'function ') + ')'
);

// ── build the real SQLite shape ────────────────────────────
const initSqlJs = require(join(REF, 'node_modules', 'sql.js'));
const SQL = await initSqlJs({
  locateFile: (f) => join(REF, 'node_modules', 'sql.js', 'dist', f),
});
const db = new SQL.Database();

createTables(db);

// The app wraps each statement in try/catch: a duplicate-column error IS how it
// detects "already applied". Same here.
let applied = 0;
for (const sql of alterStatements) {
  try { db.run(sql); applied++; } catch { /* already present */ }
}

try { migrateVaccinations(db); } catch (err) {
  console.error(`! vaccinations migration skipped: ${err.message}`);
}

const q = (sql) => {
  const out = [];
  const st = db.prepare(sql);
  while (st.step()) out.push(st.getAsObject());
  st.free();
  return out;
};

// ── translation ────────────────────────────────────────────
const SQLITE_NOW = `to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')`;

function pgType(sqliteType, isIdentity) {
  if (isIdentity) return 'bigint GENERATED BY DEFAULT AS IDENTITY';
  const t = String(sqliteType || '').toUpperCase().trim();
  if (t === 'REAL' || t === 'FLOAT' || t.startsWith('DOUBLE')) return 'double precision';
  if (t === 'INTEGER' || t === 'INT' || t === 'BIGINT') return 'bigint';
  if (t === 'DATE' || t === 'DATETIME' || t === 'TIMESTAMP') return 'text';
  if (t === 'TEXT' || t.startsWith('VARCHAR') || t.startsWith('CHAR') || t === '') return 'text';
  if (t === 'BLOB') return 'bytea';
  if (t === 'NUMERIC' || t.startsWith('DECIMAL')) return 'double precision'; // D4
  return 'text';
}

function pgDefault(raw, sqliteType) {
  if (raw === null || raw === undefined) return null;
  const v = String(raw).trim();
  if (v.toUpperCase() === 'CURRENT_TIMESTAMP') return SQLITE_NOW;
  if (v.toUpperCase() === 'NULL') return null;
  return v; // numeric and quoted-string literals carry over unchanged
}

// Quote every identifier. All names are lowercase, so this is compatible with
// the app's unquoted SQL (PostgreSQL folds unquoted identifiers to lowercase)
// while staying safe for names like "key" and "references".
const id = (s) => `"${String(s).replace(/"/g, '""')}"`;

const tables = q(
  `SELECT name, sql FROM sqlite_master
    WHERE type='table' AND name NOT LIKE 'sqlite_%'
    ORDER BY name`
);

const tableSql = [];
const stats = { tables: 0, columns: 0, real: 0, date: 0, identity: 0, composite: 0 };

for (const t of tables) {
  const cols = q(`PRAGMA table_info(${t.name})`);
  // sqlite_master holds the ORIGINAL CREATE TEXT — the only place AUTOINCREMENT
  // survives, since PRAGMA table_info does not report it.
  const isAutoinc = /AUTOINCREMENT/i.test(t.sql || '');
  const pkCols = cols.filter((c) => c.pk > 0).sort((a, b) => a.pk - b.pk);
  const singlePk = pkCols.length === 1 ? pkCols[0] : null;

  const lines = [];
  for (const c of cols) {
    const identity =
      isAutoinc &&
      singlePk &&
      c.name === singlePk.name &&
      String(c.type).toUpperCase() === 'INTEGER';

    const type = pgType(c.type, identity);
    const def = identity ? null : pgDefault(c.dflt_value, c.type);

    let line = `  ${id(c.name)} ${type}`;
    if (def !== null) line += ` DEFAULT ${def}`;
    // A single-column PK is NOT NULL implicitly; stating it twice is noise.
    if (c.notnull && !(singlePk && c.name === singlePk.name)) line += ' NOT NULL';
    lines.push(line);

    stats.columns++;
    if (type === 'double precision') stats.real++;
    if (/^(DATE|DATETIME)$/i.test(String(c.type))) stats.date++;
    if (identity) stats.identity++;
  }

  if (singlePk) {
    lines.push(`  PRIMARY KEY (${id(singlePk.name)})`);
  } else if (pkCols.length > 1) {
    lines.push(`  PRIMARY KEY (${pkCols.map((c) => id(c.name)).join(', ')})`);
    stats.composite++;
  }

  tableSql.push(`CREATE TABLE IF NOT EXISTS ${id(t.name)} (\n${lines.join(',\n')}\n);`);
  stats.tables++;
}

// ── indexes ────────────────────────────────────────────────
const indexSql = [];
for (const t of tables) {
  for (const idx of q(`PRAGMA index_list(${t.name})`)) {
    // origin 'c' = created by CREATE INDEX. 'pk'/'u' come from the table
    // definition and PostgreSQL creates those itself.
    if (idx.origin !== 'c') continue;
    const parts = q(`PRAGMA index_info(${idx.name})`)
      .sort((a, b) => a.seqno - b.seqno)
      .map((p) => id(p.name));
    if (parts.length === 0) continue;
    indexSql.push(
      `CREATE INDEX IF NOT EXISTS ${id(idx.name)} ON ${id(t.name)} (${parts.join(', ')});`
    );
  }
}

// ── emit ───────────────────────────────────────────────────
const header = (title, notes) =>
  `-- ${title}\n` +
  `-- GENERATED by db/generate-schema.mjs from "Talha Farm"/electron/database.js\n` +
  `-- Do not hand-edit: re-run the generator, review the diff, commit it.\n` +
  `--\n` +
  notes.map((n) => `-- ${n}`).join('\n') +
  `\n\n`;

const tablesFile =
  header('FarmInfantary — tables', [
    `${stats.tables} tables, ${stats.columns} columns.`,
    '',
    'Translation (docs/DECISIONS.md):',
    '  REAL     -> double precision   D4  never numeric: node-postgres returns',
    '                                     numeric as a STRING and the app does',
    '                                     plain JS arithmetic on these values.',
    '  DATE     -> text               D5  "YYYY-MM-DD", compared lexicographically.',
    '  DATETIME -> text               D5  SQLite CURRENT_TIMESTAMP format, UTC.',
    '  INTEGER  -> bigint                 SQLite INTEGER is 64-bit.',
    '',
    'NO FOREIGN KEY CONSTRAINTS (D6). They are declared throughout the desktop',
    'schema but PRAGMA foreign_keys is never enabled, so nothing has ever',
    'cascaded. The app deletes child rows manually in a deliberate order and',
    'orphan rows legitimately exist. Enforcing them here would break dozens of',
    'working delete paths.',
    '',
    'Identity columns are GENERATED BY DEFAULT, not ALWAYS, so db/import/ can',
    'write explicit ids. It must then setval() every sequence, or the first',
    'insert after an import collides.',
    '',
    'Row-level security is applied separately, in 003_rls.sql.',
  ]) + tableSql.join('\n\n') + '\n';

const indexesFile =
  header('FarmInfantary — indexes', [
    `${indexSql.length} indexes carried over from the desktop schema.`,
    '',
    'Indexes backing primary keys are omitted: PostgreSQL creates those itself.',
    '',
    'Phase 3 adds an index on every denormalised farm_id column — the row-level',
    'security policy filters on it for every row of every query.',
  ]) + indexSql.join('\n') + '\n';

if (process.argv.includes('--stdout')) {
  console.log(tablesFile);
  console.log(indexesFile);
} else {
  mkdirSync(join(HERE, 'schema'), { recursive: true });
  writeFileSync(join(HERE, 'schema', '001_tables.sql'), tablesFile);
  writeFileSync(join(HERE, 'schema', '002_indexes.sql'), indexesFile);
  console.log('Wrote db/schema/001_tables.sql and db/schema/002_indexes.sql');
}

console.error(
  `\nSource shape: ${stats.tables} tables, ${stats.columns} columns ` +
  `(${applied}/${alterStatements.length} alter statements applied)\n` +
  `  double precision : ${stats.real}   <- every one is money or a quantity\n` +
  `  date/datetime    : ${stats.date}   -> text\n` +
  `  identity columns : ${stats.identity}\n` +
  `  composite keys   : ${stats.composite}\n` +
  `  indexes          : ${indexSql.length}`
);
