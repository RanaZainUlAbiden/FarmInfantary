-- [Codex] Dedicated administration metadata; no business-table RLS exception.
ALTER TABLE farms ADD COLUMN staff_seat_limit integer NOT NULL DEFAULT 0 CHECK (staff_seat_limit>=0);
ALTER TABLE farms ADD COLUMN can_admin_add_staff integer NOT NULL DEFAULT 0 CHECK (can_admin_add_staff IN (0,1));
ALTER TABLE farms ADD COLUMN admin_version bigint NOT NULL DEFAULT 1 CHECK (admin_version>0);
CREATE FUNCTION version_changed_farm_metadata() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
 IF ROW(NEW.farm_name,NEW.business_type,NEW.status,NEW.staff_seat_limit,NEW.can_admin_add_staff)
  IS DISTINCT FROM ROW(OLD.farm_name,OLD.business_type,OLD.status,OLD.staff_seat_limit,OLD.can_admin_add_staff)
 THEN NEW.admin_version:=OLD.admin_version+1; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER farms_admin_version BEFORE UPDATE ON farms FOR EACH ROW EXECUTE FUNCTION version_changed_farm_metadata();
REVOKE ALL ON FUNCTION version_changed_farm_metadata() FROM PUBLIC;
CREATE TABLE audit_events (
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id bigint NOT NULL CHECK (actor_id>0),
 farm_id bigint CHECK (farm_id>0),
 action text NOT NULL CHECK (action IN ('farm.created','farm.updated','user.created','user.status','user.password','user.permissions')),
 target_id bigint NOT NULL CHECK (target_id>0),
 details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object'),
 created_at bigint NOT NULL DEFAULT EXTRACT(EPOCH FROM now())::bigint
);
CREATE INDEX audit_events_farm ON audit_events(farm_id,event_id);
REVOKE ALL ON audit_events FROM PUBLIC;

CREATE FUNCTION enforce_staff_seat_limit() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE previous text := current_setting('app.farm_id',true); quota integer; used bigint; needs_seat boolean;
BEGIN
 IF NEW.role='super_admin' THEN RETURN NEW; END IF;
 PERFORM set_config('app.farm_id',NEW.farm_id::text,true);
 SELECT staff_seat_limit INTO quota FROM farms WHERE farm_id=NEW.farm_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown farm' USING ERRCODE='23514'; END IF;
 needs_seat := NEW.role='staff' AND NEW.status='active';
 IF TG_OP='UPDATE' THEN
  needs_seat := needs_seat AND (OLD.role<>'staff' OR OLD.status<>'active' OR OLD.farm_id IS DISTINCT FROM NEW.farm_id);
 END IF;
 IF needs_seat THEN
  SELECT count(*) INTO used FROM users WHERE farm_id=NEW.farm_id AND role='staff' AND status='active';
  IF used>=quota THEN RAISE EXCEPTION 'Staff seat limit reached' USING ERRCODE='23514'; END IF;
 END IF;
 PERFORM set_config('app.farm_id',COALESCE(previous,''),true);
 RETURN NEW;
EXCEPTION WHEN OTHERS THEN
 PERFORM set_config('app.farm_id',COALESCE(previous,''),true); RAISE;
END;
$$;
CREATE TRIGGER users_staff_seats BEFORE INSERT OR UPDATE OF farm_id,role,status ON users
 FOR EACH ROW EXECUTE FUNCTION enforce_staff_seat_limit();
REVOKE ALL ON FUNCTION enforce_staff_seat_limit() FROM PUBLIC;

-- Private per-farm accessor, like auth_farm_metadata: explicit ID/context,
-- qualified relations, fixed path, no credential/business data, no PUBLIC access.
DO $install$
DECLARE target text := current_schema();
BEGIN
 EXECUTE format($create$
  CREATE FUNCTION %I.admin_farm_metadata(requested_farm bigint)
  RETURNS TABLE(farm_id bigint,farm_name text,business_type text,status text,staff_seat_limit integer,can_admin_add_staff integer,admin_version bigint,active_staff bigint)
  LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $body$
  DECLARE previous text := current_setting('app.farm_id',true);
  BEGIN
   IF requested_farm IS NULL OR requested_farm<=0 THEN RETURN; END IF;
   PERFORM set_config('app.farm_id',requested_farm::text,true);
   RETURN QUERY EXECUTE %L USING requested_farm;
   PERFORM set_config('app.farm_id',COALESCE(previous,''),true);
  EXCEPTION WHEN OTHERS THEN
   PERFORM set_config('app.farm_id',COALESCE(previous,''),true); RAISE;
  END;
  $body$;
 $create$,target,format('SELECT f.farm_id,f.farm_name,f.business_type,f.status,f.staff_seat_limit,f.can_admin_add_staff,f.admin_version,(SELECT count(*) FROM %I.users u WHERE u.farm_id=f.farm_id AND u.role=''staff'' AND u.status=''active'') FROM %I.farms f WHERE f.farm_id=$1',target,target));
 EXECUTE format('REVOKE ALL ON FUNCTION %I.admin_farm_metadata(bigint) FROM PUBLIC',target);
END;
$install$;
