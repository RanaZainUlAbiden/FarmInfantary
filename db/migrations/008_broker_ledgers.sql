REVOKE ALL ON broker_payments FROM PUBLIC;
-- Only copy the already attested business role's narrow DML grants, never auth.
DO $$
DECLARE grantee_name text;
BEGIN
 FOR grantee_name IN SELECT grantee FROM information_schema.table_privileges
  WHERE table_schema=current_schema() AND table_name='brokers' AND privilege_type='INSERT' AND grantee<>current_user AND grantee<>'PUBLIC' LOOP
  EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON broker_payments TO %I',grantee_name);
  EXECUTE format('GRANT USAGE ON SEQUENCE broker_payments_payment_id_seq TO %I',grantee_name);
 END LOOP;
END $$;
