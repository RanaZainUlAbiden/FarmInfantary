DO $$
DECLARE tenant bigint;
BEGIN
 FOR tenant IN SELECT DISTINCT farm_id FROM users WHERE farm_id IS NOT NULL LOOP
  PERFORM set_config('app.farm_id',tenant::text,true);
  INSERT INTO brokers(farm_id,broker_name)
   SELECT tenant,trim(s.broker) FROM sales s
   WHERE s.farm_id=tenant AND COALESCE(s.module_type,'broiler')='broiler' AND trim(COALESCE(s.broker,''))<>''
    AND NOT EXISTS(SELECT 1 FROM brokers b WHERE b.farm_id=tenant AND lower(trim(b.broker_name))=lower(trim(s.broker)))
   GROUP BY trim(s.broker);
  UPDATE brokers b SET merged_into=c.id FROM
   (SELECT lower(trim(broker_name)) AS name,min(broker_id) AS id FROM brokers WHERE farm_id=tenant GROUP BY lower(trim(broker_name))) c
   WHERE b.farm_id=tenant AND lower(trim(b.broker_name))=c.name AND b.broker_id<>c.id;
  UPDATE sales s SET broker_id=b.broker_id FROM brokers b
   WHERE s.farm_id=tenant AND b.farm_id=tenant AND b.merged_into IS NULL
    AND lower(trim(s.broker))=lower(trim(b.broker_name)) AND COALESCE(s.module_type,'broiler')='broiler';
 END LOOP;
END $$;
CREATE UNIQUE INDEX broker_unique_name ON brokers(farm_id,lower(trim(broker_name))) WHERE merged_into IS NULL;
CREATE INDEX broker_sales_scope ON sales(farm_id,broker_id,flock_id);
CREATE TABLE broker_payments (
 payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farm_id bigint NOT NULL,
 broker_id bigint NOT NULL,
 flock_id bigint NOT NULL,
 sale_id bigint NOT NULL,
 date text NOT NULL,
 amount double precision NOT NULL CHECK(amount>0 AND amount<'Infinity'::double precision),
 method text NOT NULL CHECK(method IN ('cash','bank','other')),
 bank_id bigint,
 reference text NOT NULL DEFAULT '',
 note text NOT NULL DEFAULT '',
 request_id text NOT NULL,
 request_hash text NOT NULL,
 reversed integer NOT NULL DEFAULT 0 CHECK(reversed IN(0,1)),
 UNIQUE(farm_id,request_id)
);
CREATE INDEX broker_payments_farm ON broker_payments(farm_id,broker_id,flock_id,sale_id);
