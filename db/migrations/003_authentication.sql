-- [Codex] Platform identity is separate from the 60 inherited business tables.
-- No desktop logins/password hashes are imported under D14.
ALTER TABLE farms ADD COLUMN status text NOT NULL DEFAULT 'active'
  CHECK (status IN ('active', 'suspended'));

CREATE TABLE users (
  user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id bigint,
  username text NOT NULL CHECK (username ~ '^[A-Za-z0-9][A-Za-z0-9._-]{2,63}$'),
  password_hash text NOT NULL CHECK (password_hash LIKE '$argon2id$%'),
  role text NOT NULL CHECK (role IN ('super_admin','farm_admin','staff')),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended')),
  auth_version bigint NOT NULL DEFAULT 1 CHECK (auth_version > 0),
  created_at bigint NOT NULL DEFAULT EXTRACT(EPOCH FROM now())::bigint,
  CHECK ((role = 'super_admin' AND farm_id IS NULL) OR
         (role IN ('farm_admin','staff') AND farm_id > 0 AND farm_id IS NOT NULL))
);
CREATE UNIQUE INDEX users_username_unique ON users (lower(username));
CREATE INDEX users_farm ON users(farm_id);

CREATE TABLE auth_sessions (
  token_hash text PRIMARY KEY CHECK (token_hash ~ '^[a-f0-9]{64}$'),
  user_id bigint NOT NULL,
  auth_version bigint NOT NULL,
  created_at bigint NOT NULL,
  last_seen_at bigint NOT NULL,
  expires_at bigint NOT NULL,
  CHECK (last_seen_at >= created_at AND expires_at > created_at)
);
CREATE INDEX auth_sessions_user ON auth_sessions(user_id);
CREATE INDEX auth_sessions_expiry ON auth_sessions(expires_at);

-- HMAC bucket identifiers, never raw usernames or IP addresses.
CREATE TABLE auth_login_limits (
  bucket text PRIMARY KEY,
  window_started_at bigint NOT NULL,
  attempts bigint NOT NULL CHECK (attempts > 0)
);
CREATE INDEX auth_login_limits_window ON auth_login_limits(window_started_at);

-- Revocation survives later reactivation and applies even when a trusted admin
-- updates rows directly. Normal profile saves with identical values do not log
-- users out. The password endpoint also explicitly removes all device sessions.
CREATE FUNCTION revoke_changed_user_identity() RETURNS trigger LANGUAGE plpgsql
SET search_path FROM CURRENT AS $$
BEGIN
  IF ROW(NEW.username,NEW.password_hash,NEW.role,NEW.status,NEW.farm_id)
     IS DISTINCT FROM ROW(OLD.username,OLD.password_hash,OLD.role,OLD.status,OLD.farm_id) THEN
    NEW.auth_version := OLD.auth_version + 1;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER users_identity_revocation BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION revoke_changed_user_identity();

CREATE FUNCTION revoke_changed_farm_status() RETURNS trigger LANGUAGE plpgsql
SET search_path FROM CURRENT AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    UPDATE users SET auth_version=auth_version+1 WHERE farm_id=NEW.farm_id;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER farms_status_revocation AFTER UPDATE OF status ON farms
  FOR EACH ROW EXECUTE FUNCTION revoke_changed_farm_status();
