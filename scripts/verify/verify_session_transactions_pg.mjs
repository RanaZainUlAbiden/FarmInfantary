// [Codex] Transaction ownership and pooled context, against a real non-owner
// NOBYPASSRLS role. The tiny fixture authorizer is NOT the production AST guard.
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { createRequire } from 'node:module';
import { setTimeout as delay } from 'node:timers/promises';
import { loadEnv, createScratchDb } from './lib/pg-harness.mjs';
import { createSessionDb } from '../../server/src/db/session-execute.js';
import { createDb } from '../../server/src/db/execute.js';
const require = createRequire(new URL('../../server/package.json', import.meta.url));
const pg = require('pg');
if (!loadEnv()) throw new Error('DATABASE_URL is required to verify session transactions');
const fixture = await createScratchDb('sessiontx');
const role = 'vp_session_' + randomBytes(8).toString('hex');
const runtime = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: 4,
  options: `-c search_path=${fixture.schema},public` });
// Await role selection before exposing the connection (not an async connect
// event, which pg.Pool does not await). The production role will be a login.
const pool = { async connect() {
  const client = await runtime.connect();
  try { await client.query(`SET ROLE "${role}"`); return client; }
  catch (error) { client.release(error); throw error; }
}};
const actor = (farmId, userId, sessionKey = randomBytes(32).toString('hex')) =>
  ({ farmId, userId, sessionKey, authVersion: 1, role: 'farm_admin' });
const a = actor(1, 10), otherDevice = actor(1, 10), b = actor(2, 20);
const insert = 'INSERT INTO session_fixture(farm_id,value) VALUES(?,?)';
const read = 'SELECT * FROM session_fixture ORDER BY id';
const context = "SELECT current_setting('app.farm_id') AS farm, current_setting('app.user_id') AS usr";
const update = 'UPDATE session_fixture SET value=value+? WHERE id=?';
const slow = 'SELECT pg_sleep(?)'; // explicitly fixture-only, forbidden by the real SQL guard
const allowed = new Set([insert, read, context, update, slow, 'SELECT 1/0', 'SELECT 42 AS answer']);
const options = { authorize: ({ sql }) => allowed.has(sql), maxConnections: 3 };
let db, timed, bounded, roleCreated = false, checks = 0;
const ok = result => { assert.equal(result.success, true, result.error); return result; };
const no = result => { assert.equal(result.success, false); return result; };
async function check(label, fn) { await fn(); checks++; console.log('  PASS  ' + label); }
async function until(test, label) {
  const deadline = Date.now() + 3000;
  while (!await test()) { if (Date.now() > deadline) throw new Error('Timed out: ' + label); await delay(5); }
}
const sleeping = async () => Number((await fixture.pool.query(`SELECT count(*) FROM pg_stat_activity
  WHERE query=$1 AND state='active' AND pid<>pg_backend_pid()`, ['SELECT pg_sleep($1)'])).rows[0].count) > 0;
async function count(farm, value) {
  return Number((await fixture.pool.query('SELECT count(*) FROM session_fixture WHERE farm_id=$1 AND value=$2', [farm, value])).rows[0].count);
}
try {
  await fixture.pool.query(`CREATE ROLE "${role}" NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS`);
  roleCreated = true;
  await fixture.pool.query(`CREATE TABLE session_fixture(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id bigint NOT NULL, value integer NOT NULL CHECK(value>=0));
    ALTER TABLE session_fixture ENABLE ROW LEVEL SECURITY;
    ALTER TABLE session_fixture FORCE ROW LEVEL SECURITY;
    CREATE POLICY own_farm ON session_fixture USING(farm_id=NULLIF(current_setting('app.farm_id',true),'')::bigint)
      WITH CHECK(farm_id=NULLIF(current_setting('app.farm_id',true),'')::bigint);
    GRANT USAGE ON SCHEMA "${fixture.schema}" TO "${role}";
    GRANT SELECT,INSERT,UPDATE,DELETE ON session_fixture TO "${role}";
    GRANT USAGE,SELECT ON SEQUENCE session_fixture_id_seq TO "${role}";`);
  db = createSessionDb(pool, options); await db.init();
  const A = db.forActor(a), B = db.forActor(b), D = db.forActor(otherDevice);
  await check('fixture runtime is a non-owner role without superuser or RLS bypass', async () => {
    const client = await pool.connect();
    try {
      const row = (await client.query(`SELECT r.rolsuper,r.rolbypassrls,c.relowner=r.oid AS owns
        FROM pg_roles r CROSS JOIN pg_class c WHERE r.rolname=current_user AND c.oid='session_fixture'::regclass`)).rows[0];
      assert.deepEqual(row, { rolsuper: false, rolbypassrls: false, owns: false });
    } finally { client.release(); }
  });
  await check('missing authorizer and invalid limits refuse construction', async () => {
    assert.throws(() => createSessionDb(pool), /authorizer/);
    assert.throws(() => createSessionDb(pool, { ...options, lifetimeMs: 0 }), /limit/);
  });
  await check('missing, forged, unsafe and platform identities cannot acquire a connection', async () => {
    for (const invalid of [null, {}, { ...a, farmId: 0 }, { ...a, role: 'super_admin' },
      { ...a, sessionKey: 'cookie-token' }, { ...a, userId: Number.MAX_SAFE_INTEGER + 1 }, { ...a, farmId: '1;SET ROLE postgres' }]) {
      no(await db.forActor(invalid).begin()); no(await db.forActor(invalid).get(read));
    }
    assert.equal(db.activeConnections, 0);
  });
  await check('every short operation gets transaction-local server context', async () => {
    assert.deepEqual(ok(await A.get(context)).data[0], { farm: '1', usr: '10' });
    assert.deepEqual(ok(await B.get(context)).data[0], { farm: '2', usr: '20' });
    assert.equal(db.activeConnections, 0);
  });
  await check('concurrent pooled reads cannot borrow another farm context', async () => {
    const results = await Promise.all([A.get(context), B.get(context), D.get(context)]);
    assert.deepEqual(results.map(r => ok(r).data[0].farm), ['1', '2', '1']);
  });
  await check('commits preserve lastId and FORCE RLS hides rows without client WHERE filters', async () => {
    const x = ok(await A.run(insert, [1, 100])); assert.ok(x.lastId > 0);
    ok(await B.run(insert, [2, 200]));
    assert.deepEqual(ok(await A.get(read)).data.map(r => r.value), [100]);
    assert.deepEqual(ok(await B.get(read)).data.map(r => r.value), [200]);
  });
  await check('forged farm inserts fail without row creation or database-detail leakage', async () => {
    const result = no(await A.run(insert, [2, 999])); assert.equal(result.error, 'Database operation failed.');
    assert.equal(await count(2, 999), 0);
  });
  await check('pool reuse has no farm/user context after commit or rollback', async () => {
    no(await A.get('SELECT 1/0'));
    const clients = await Promise.all([pool.connect(), pool.connect(), pool.connect()]);
    try {
      for (const client of clients) {
        const row = (await client.query("SELECT NULLIF(current_setting('app.farm_id',true),'') AS farm, NULLIF(current_setting('app.user_id',true),'') AS usr")).rows[0];
        assert.deepEqual(row, { farm: null, usr: null });
        assert.equal((await client.query('SELECT * FROM session_fixture')).rows.length, 0);
      }
    } finally { clients.forEach(c => c.release()); }
  });
  await check('tokens are opaque and every operation is bound to one device session', async () => {
    const token = ok(await A.begin()).token; assert.match(token, /^[A-Za-z0-9_-]{43}$/);
    for (const intruder of [B, D]) {
      no(await intruder.get(read, [], token)); no(await intruder.run(insert, [1, 666], token));
      no(await intruder.batch([{ sql: insert, params: [1, 666] }], token));
      no(await intruder.commit(token)); no(await intruder.rollback(token));
    }
    ok(await A.run(insert, [1, 101], token)); assert.equal(await count(1, 101), 0);
    ok(await A.commit(token)); assert.equal(await count(1, 101), 1); no(await A.commit(token));
  });
  await check('one explicit transaction per session is reserved before asynchronous BEGIN', async () => {
    const results = await Promise.all([A.begin(), A.begin()]);
    assert.equal(results.filter(r => r.success).length, 1);
    no(await A.begin()); ok(await A.rollback(results.find(r => r.success).token));
  });
  await check('caller mutation cannot change a captured server identity', async () => {
    const mutable = { ...a }, fixed = db.forActor(mutable); mutable.farmId = 2; mutable.userId = 20;
    assert.deepEqual(ok(await fixed.get(context)).data[0], { farm: '1', usr: '10' });
  });
  await check('changed farm, role or auth version invalidates the old session transaction', async () => {
    for (const change of [{ farmId: 2 }, { role: 'staff' }, { authVersion: 2 }]) {
      const token = ok(await A.begin()).token;
      ok(await A.run(insert, [1, 102], token)); no(await db.forActor({ ...a, ...change }).commit(token));
      await db.revokeSession(a.sessionKey); no(await A.commit(token));
    }
    assert.equal(await count(1, 102), 0);
  });
  await check('all batch authorization happens before the first write', async () => {
    no(await A.batch([{ sql: insert, params: [1, 103] }, { sql: 'DROP TABLE session_fixture' }]));
    assert.equal(await count(1, 103), 0); assert.equal(db.activeConnections, 0);
  });
  await check('standalone batches are atomic and preserve lastId back-references', async () => {
    const result = ok(await A.batch([{ sql: insert, params: [1, 104] },
      { sql: update, params: [1, { $lastId: -1 }] }]));
    assert.ok(result.results[0].lastId > 0); assert.equal(await count(1, 105), 1);
    const failed = no(await A.batch([{ sql: insert, params: [1, 106] }, { sql: insert, params: [1, -1] }]));
    assert.equal(failed.failedIndex, 1); assert.equal(failed.failedSql, undefined); assert.equal(await count(1, 106), 0);
  });
  await check('nested batch failure restores savepoint and allows the outer transaction to commit', async () => {
    const token = ok(await A.begin()).token; ok(await A.run(insert, [1, 107], token));
    no(await A.batch([{ sql: insert, params: [1, 108] }, { sql: insert, params: [1, -1] }], token));
    ok(await A.run(insert, [1, 109], token)); ok(await A.commit(token));
    assert.equal(await count(1, 107), 1); assert.equal(await count(1, 108), 0); assert.equal(await count(1, 109), 1);
  });
  await check('concurrent operations serialize before commit, with no savepoint interleaving', async () => {
    const token = ok(await A.begin()).token;
    const jobs = [A.batch([{ sql: insert, params: [1, 110] }], token), A.batch([{ sql: insert, params: [1, 111] }], token)];
    // Give authorization promises time to admit both requests, then commit.
    await delay(10); jobs.push(A.commit(token));
    (await Promise.all(jobs)).forEach(ok); assert.equal(await count(1, 110), 1); assert.equal(await count(1, 111), 1);
  });
  await check('ordinary SQL failure rolls back and cannot later report a successful commit', async () => {
    const token = ok(await A.begin()).token; ok(await A.run(insert, [1, 112], token));
    no(await A.get('SELECT 1/0', [], token)); no(await A.commit(token));
    await db.revokeSession(a.sessionKey); assert.equal(await count(1, 112), 0);
  });
  await check('session revocation rolls back only that device and user revocation closes every device', async () => {
    const ta = ok(await A.begin()).token, td = ok(await D.begin()).token, tb = ok(await B.begin()).token;
    ok(await A.run(insert, [1, 113], ta)); ok(await D.run(insert, [1, 114], td));
    await db.revokeSession(a.sessionKey); no(await A.commit(ta)); ok(await D.get(context, [], td));
    await db.revokeUser(a.userId); no(await D.commit(td)); ok(await B.commit(tb));
    assert.equal(await count(1, 113), 0); assert.equal(await count(1, 114), 0);
  });
  await check('admission limits bound open connections and per-user transactions', async () => {
    bounded = createSessionDb(pool, { ...options, maxConnections: 2, maxTransactionsPerUser: 1 }); await bounded.init();
    const x = bounded.forActor(a), y = bounded.forActor(b), z = bounded.forActor(otherDevice);
    const tx = ok(await x.begin()).token; no(await z.begin()); const ty = ok(await y.begin()).token;
    no(await z.get(read)); assert.equal(bounded.activeConnections, 2);
    ok(await x.rollback(tx)); ok(await y.rollback(ty));
  });
  await check('statement timeout rolls back, releases capacity and sanitizes details', async () => {
    timed = createSessionDb(pool, { ...options, statementTimeoutMs: 50, idleTimeoutMs: 300, lifetimeMs: 900 }); await timed.init();
    const T = timed.forActor(a); assert.equal(no(await T.get(slow, [0.2])).error, 'Database operation failed.');
    assert.equal(timed.activeConnections, 0); ok(await T.get(context)); await timed.close();
  });
  await check('idle timeout rolls back abandoned writes and invalidates the token', async () => {
    timed = createSessionDb(pool, { ...options, idleTimeoutMs: 60, lifetimeMs: 900 }); await timed.init();
    const T = timed.forActor(a), token = ok(await T.begin()).token; ok(await T.run(insert, [1, 115], token));
    await delay(140); no(await T.commit(token)); assert.equal(await count(1, 115), 0); assert.equal(timed.activeConnections, 0); await timed.close();
  });
  await check('absolute lifetime expires even while the caller keeps the transaction active', async () => {
    timed = createSessionDb(pool, { ...options, idleTimeoutMs: 500, lifetimeMs: 160 }); await timed.init();
    const T = timed.forActor(a), token = ok(await T.begin()).token;
    for (let i = 0; i < 6; i++) { await delay(45); await T.get(context, [], token); }
    no(await T.commit(token)); assert.equal(timed.activeConnections, 0); await timed.close();
  });
  await check('queue capacity rejects excess work without interleaving a pending commit', async () => {
    timed = createSessionDb(pool, { ...options, maxQueuedOperations: 1 }); await timed.init();
    const T = timed.forActor(a), token = ok(await T.begin()).token;
    const running = T.get(slow, [0.15], token); await until(sleeping, 'active fixture query');
    no(await T.get(context, [], token)); const finishing = T.commit(token);
    no(await T.run(insert, [1, 117], token)); ok(await running); ok(await finishing);
    assert.equal(await count(1, 117), 0); await timed.close();
  });
  await check('revocation cancels queued writes and a commit already waiting behind a query', async () => {
    const token = ok(await A.begin()).token; ok(await A.run(insert, [1, 118], token));
    const running = A.get(slow, [0.15], token); await until(sleeping, 'active query before revoke');
    const queued = A.run(insert, [1, 119], token);
    await delay(5); const finishing = A.commit(token); const revoked = db.revokeSession(a.sessionKey);
    no(await running); no(await queued); no(await finishing); await revoked;
    assert.equal(await count(1, 118), 0); assert.equal(await count(1, 119), 0);
  });
  await check('absolute deadline also applies while commit waits for admitted work', async () => {
    timed = createSessionDb(pool, { ...options, lifetimeMs: 80, idleTimeoutMs: 500 }); await timed.init();
    const T = timed.forActor(a), token = ok(await T.begin()).token;
    ok(await T.run(insert, [1, 120], token)); const running = T.get(slow, [0.2], token);
    await until(sleeping, 'active query before deadline'); const finishing = T.commit(token);
    no(await running); no(await finishing); assert.equal(await count(1, 120), 0); await timed.close();
  });
  await check('shutdown during asynchronous BEGIN cannot leak an untracked lease', async () => {
    const client = await pool.connect(); let releaseBegin, entered;
    const began = new Promise(resolve => { entered = resolve; });
    const resume = new Promise(resolve => { releaseBegin = resolve; });
    const waitingPool = { async connect() { entered(); await resume; return client; } };
    const pending = createSessionDb(waitingPool, options);
    const opening = pending.forActor(a).begin(); await began;
    const closing = pending.close(); releaseBegin(); no(await opening); await closing;
    assert.equal(pending.activeConnections, 0);
  });
  await check('shutdown rejects new admissions and rolls back all outstanding writes', async () => {
    const token = ok(await A.begin()).token; ok(await A.run(insert, [1, 116], token)); await db.close();
    no(await A.begin()); no(await A.get(read)); assert.equal(db.activeConnections, 0); assert.equal(await count(1, 116), 0);
  });
  await check('an aborted raw PostgreSQL transaction cannot commit with a success result', async () => {
    const raw = createDb(pool); await raw.init(); const token = ok(await raw.begin()).token;
    no(await raw.get('SELECT 1/0', [], token)); no(await raw.commit(token)); assert.equal(raw.openTransactions, 0);
  });
  console.log(`\nALL CHECKS PASSED — ${checks} session transaction scenarios`);
} finally {
  await Promise.all([db?.close(), timed?.close(), bounded?.close()]);
  await runtime.end();
  await fixture.close();
  if (roleCreated) {
    const admin = new pg.Pool({ connectionString: process.env.DATABASE_URL });
    try { await admin.query(`DROP ROLE "${role}"`); } finally { await admin.end(); }
  }
}
