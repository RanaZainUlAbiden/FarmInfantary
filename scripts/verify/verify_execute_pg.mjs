// The query layer, end to end, against a real PostgreSQL database.
//
// Everything here is about the CONTRACT 341 call sites were written against:
//
//   get   -> { success: true, data: rows[] }
//   run   -> { success: true, lastId }
//   batch -> { success: true, results: [{ lastId }], lastId }
//   failure -> { success: false, error }   NEVER a thrown/rejected promise
//
// The last line is the one most easily broken by a port. On the desktop a
// failure came back as a result object and every call site checks `.success`.
// If this layer started rejecting, error handling across the whole app would
// silently change shape.
//
// Runs inside a transaction that is rolled back, so it leaves nothing behind.
// Skips (exit 0) when no database is configured.

import { readFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const require = createRequire(import.meta.url)

const envPath = join(ROOT, '.env')
if (existsSync(envPath)) {
  for (const line of readFileSync(envPath, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)\s*$/)
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].trim()
  }
}

const url = process.env.DATABASE_URL
if (!url) { console.log('SKIP — no DATABASE_URL configured'); process.exit(0) }

let pg, createDb
try {
  pg = require(join(ROOT, 'server', 'node_modules', 'pg'))
  ;({ createDb } = await import(new URL('../../server/src/db/execute.js', import.meta.url)))
  const t = await import(new URL('../../server/src/db/types.js', import.meta.url))
  t.registerTypeParsers(pg)
} catch (err) {
  console.log(`SKIP — server deps not available (${err.message})`)
  process.exit(0)
}

let passed = 0
const failures = []
const check = (label, cond, detail) => {
  if (cond) { passed++; console.log(`  PASS  ${label}`) }
  else { failures.push(label); console.log(`  FAIL  ${label}${detail ? ` — ${detail}` : ''}`) }
}

// A pool whose every connection is pinned to one rolled-back transaction would
// be complex; instead use a real pool on a scratch SCHEMA, dropped at the end.
const pool = new pg.Pool({ connectionString: url, max: 4 })
const SCHEMA = `vtest_${Date.now().toString(36)}`

const admin = await pool.connect()
await admin.query(`CREATE SCHEMA ${SCHEMA}`)
await admin.query(`SET search_path TO ${SCHEMA}`)
// A miniature of the real shape: identity pk, a composite-key table, money.
await admin.query(`
  CREATE TABLE ${SCHEMA}.bills (
    bill_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id bigint NOT NULL,
    total_amount double precision DEFAULT 0,
    amount_paid double precision DEFAULT 0
  );
  CREATE TABLE ${SCHEMA}.bill_items (
    item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id bigint NOT NULL,
    product_name text NOT NULL,
    total_price double precision DEFAULT 0
  );
  CREATE TABLE ${SCHEMA}.app_settings (
    farm_id bigint NOT NULL, key text NOT NULL, value text,
    PRIMARY KEY (farm_id, key)
  );`)
admin.release()

// Every pooled connection must see the scratch schema.
pool.on('connect', (c) => c.query(`SET search_path TO ${SCHEMA}, public`))

const db = createDb(pool)

try {
  console.log('Query layer against PostgreSQL')
  console.log('='.repeat(62))

  console.log('\n=== A. primary keys load from the catalogue ===')
  const n = await db.init()
  check(`loaded ${n} single-column integer keys`, n >= 2, `got ${n}`)

  console.log('\n=== B. run() and get() ===')
  const ins = await db.run(
    `INSERT INTO bills (farm_id, total_amount, amount_paid) VALUES (?, ?, ?)`,
    [1, 1000.5, 400.25]
  )
  check('run() reports success', ins.success === true, JSON.stringify(ins))
  check('run() returns a lastId from RETURNING', typeof ins.lastId === 'number', `got ${typeof ins.lastId}`)

  const sel = await db.get(`SELECT total_amount, amount_paid FROM bills WHERE bill_id = ?`, [ins.lastId])
  check('get() returns { success, data }', sel.success === true && Array.isArray(sel.data))
  check('get() found the inserted row', sel.data.length === 1, `got ${sel.data.length}`)
  check('money came back as a NUMBER', typeof sel.data[0]?.total_amount === 'number',
    `got ${typeof sel.data[0]?.total_amount}`)

  console.log('\n=== C. errors are RESULTS, never rejections ===')
  // This is the contract most easily broken by a port.
  for (const [label, sql, params] of [
    ['a syntax error', `SELEKT 1`, []],
    ['an unknown table', `SELECT * FROM does_not_exist`, []],
    ['an untranslatable construct', `SELECT last_insert_rowid()`, []],
    ['a param count mismatch', `SELECT * FROM bills WHERE farm_id = ? AND bill_id = ?`, [1]],
  ]) {
    let threw = false
    let r
    try { r = await db.get(sql, params) } catch { threw = true }
    check(`${label} resolves rather than throwing`, !threw)
    check(`${label} returns success:false with a message`,
      r && r.success === false && typeof r.error === 'string' && r.error.length > 0,
      JSON.stringify(r))
  }

  console.log('\n=== D. batch: atomic, with $lastId back-references ===')
  const b = await db.batch([
    { sql: `INSERT INTO bills (farm_id, total_amount) VALUES (?, ?)`, params: [2, 500] },
    { sql: `INSERT INTO bill_items (bill_id, product_name, total_price) VALUES (?, ?, ?)`,
      params: [{ $lastId: -1 }, 'Feed', 300] },
    { sql: `INSERT INTO bill_items (bill_id, product_name, total_price) VALUES (?, ?, ?)`,
      params: [{ $lastId: -2 }, 'Medicine', 200] },
  ])
  check('batch reports success', b.success === true, JSON.stringify(b))
  check('batch returns one result per statement', b.results?.length === 3, `got ${b.results?.length}`)
  check('batch lastId is the final statement\'s', b.lastId === b.results?.[2]?.lastId)

  const items = await db.get(
    `SELECT bill_id, product_name FROM bill_items WHERE bill_id = ? ORDER BY item_id`,
    [b.results[0].lastId]
  )
  check('$lastId -1 and -2 both resolved to the bill', items.data.length === 2, `got ${items.data.length}`)

  console.log('\n=== E. a failed batch writes NOTHING ===')
  const before = await db.get(`SELECT COUNT(*)::int AS n FROM bills`, [])
  const bad = await db.batch([
    { sql: `INSERT INTO bills (farm_id, total_amount) VALUES (?, ?)`, params: [3, 10] },
    { sql: `INSERT INTO bills (farm_id, total_amount) VALUES (?, ?)`, params: [3, 20] },
    { sql: `INSERT INTO nope (x) VALUES (?)`, params: [1] },
  ])
  const after = await db.get(`SELECT COUNT(*)::int AS n FROM bills`, [])
  check('a failing batch reports success:false', bad.success === false)
  check('it names the failing statement (1-based in the message)',
    /statement 3 of 3/.test(bad.error ?? ''), bad.error)
  check('failedIndex is 0-based', bad.failedIndex === 2, `got ${bad.failedIndex}`)
  check('the earlier inserts were rolled back',
    before.data[0].n === after.data[0].n, `${before.data[0].n} -> ${after.data[0].n}`)

  console.log('\n=== F. $lastId pointing at a row that was never inserted ===')
  // Writing null into a foreign key is the desktop landmine. Refuse instead.
  const orphan = await db.batch([
    { sql: `INSERT INTO app_settings (farm_id, key, value) VALUES (?, ?, ?)`, params: [1, 'k', 'v'] },
    { sql: `INSERT INTO bill_items (bill_id, product_name) VALUES (?, ?)`,
      params: [{ $lastId: -1 }, 'orphan'] },
  ])
  check('refused rather than writing a null foreign key', orphan.success === false)
  check('the error explains why', /inserted no row and produced no id/.test(orphan.error ?? ''), orphan.error)

  console.log('\n=== G. transactions spanning several calls ===')
  const tx = await db.begin()
  check('begin() returns a token', tx.success === true && typeof tx.token === 'string')

  await db.run(`INSERT INTO bills (farm_id, total_amount) VALUES (?, ?)`, [9, 77], tx.token)
  const inside = await db.get(`SELECT COUNT(*)::int AS n FROM bills WHERE farm_id = ?`, [9], tx.token)
  check('a write is visible inside its own transaction', inside.data[0].n === 1, `got ${inside.data[0].n}`)

  const outside = await db.get(`SELECT COUNT(*)::int AS n FROM bills WHERE farm_id = ?`, [9])
  check('and NOT visible outside it', outside.data[0].n === 0, `got ${outside.data[0].n}`)

  const rb = await db.rollback(tx.token)
  check('rollback succeeds', rb.success === true)
  const afterRb = await db.get(`SELECT COUNT(*)::int AS n FROM bills WHERE farm_id = ?`, [9])
  check('rolled-back work is gone', afterRb.data[0].n === 0, `got ${afterRb.data[0].n}`)
  check('no transaction is left open', db.openTransactions === 0, `got ${db.openTransactions}`)

  const stale = await db.commit(tx.token)
  check('committing a finished transaction is refused, not thrown', stale.success === false)

  console.log('\n=== H. a batch INSIDE a transaction uses a savepoint ===')
  const tx2 = await db.begin()
  await db.run(`INSERT INTO bills (farm_id, total_amount) VALUES (?, ?)`, [11, 1], tx2.token)
  const nestedBad = await db.batch(
    [{ sql: `INSERT INTO nope (x) VALUES (?)`, params: [1] }],
    tx2.token
  )
  check('the nested batch fails', nestedBad.success === false)
  const survived = await db.get(
    `SELECT COUNT(*)::int AS n FROM bills WHERE farm_id = ?`, [11], tx2.token)
  check('but the surrounding transaction survives it', survived.success === true && survived.data[0].n === 1,
    JSON.stringify(survived))
  await db.rollback(tx2.token)
} finally {
  const cleanup = await pool.connect()
  await cleanup.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`)
  cleanup.release()
  await pool.end()
}

console.log('\n' + '='.repeat(62))
if (failures.length) {
  console.log(`FAILED — ${failures.length} check(s):`)
  for (const f of failures) console.log(`  - ${f}`)
  process.exit(1)
}
console.log(`ALL CHECKS PASSED — ${passed} checks against PostgreSQL`)
