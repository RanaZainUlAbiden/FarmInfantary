// A generated review worksheet, deliberately not imported by server code.
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {ROOT,currentCatalogue} from './permission-catalogue.mjs';
import {applicationSourceDigest,traceProducerDigest} from './permission-trace.mjs';
const catalogue=currentCatalogue(),evidence=JSON.parse(readFileSync(resolve(ROOT,'tools/permission-evidence/vouchers.json'),'utf8'));
if(evidence.sourceDigest!==applicationSourceDigest()||evidence.producerDigest!==traceProducerDigest()||evidence.catalogueDigest!==catalogue.sourceDigest||!evidence.regressionPassed||evidence.scopes.some(s=>s.unresolved))throw new Error('Cannot report stale or unresolved evidence');
const known=new Set(catalogue.entries.map(e=>e.key));
if(evidence.scopes.some(s=>!known.has(s.key)||!['view','create','edit','delete'].includes(s.action)))throw new Error('Unknown trace scope');
const observed=new Set(evidence.scopes.map(s=>s.key));
const tableSet=(scope,type)=>[...new Set(scope.observations.flatMap(o=>type==='read'?o.readTables:Object.keys(o.writeTables)))].sort().join(', ');
const rows=evidence.scopes.map(s=>'| '+[s.key,s.action,s.invocations,s.failedWorkflows,tableSet(s,'read'),tableSet(s,'write')].join(' | ')+' |');
const out=`# Permission table observations — generated by Codex

Run \`node tools/permission-report.mjs\` to regenerate. This is an incomplete
review worksheet, **not an authorization policy**. No server file imports it.

The current sidebar derives **${catalogue.entries.length} keys**: 14 broiler, 15 layer,
15 distribution and 6 owner. Add Batch is a shortcut onto Batches. The older
47-key estimate is superseded by these measured current menus.

Real PostgreSQL voucher regressions provide **${evidence.scopes.length} action scopes across
${observed.size}/${catalogue.entries.length} screens**. These observations include refused workflows and
their reads; SQL recorded by a failed attempt is not proof of a successful write.
Setup/fixture SQL outside explicitly labeled workflows is excluded. Action
intent comes from the real application entry point, never from the SQL verb.

| Permission | Action | Invocations | Refused workflows | Observed reads | Observed writes |
|---|---|---:|---:|---|---|
${rows.join('\n')}

Evidence: \`tools/permission-evidence/vouchers.json\`; scenarios include bank/cash
and overpayment/deletion cases in \`verify_vouchers_pg.mjs\`. Query text, parameter
values, rows and database error details are not saved. Only query hashes, table
names, operation kinds and counters persist. The source digest is
\`${evidence.sourceDigest}\`.

## Unobserved screen keys

${catalogue.entries.filter(p=>!observed.has(p.key)).map(p=>'- '+p.key).join('\n')}

## Required before activation

Complete each applicable view/create/edit/delete workflow and dependency route,
including failure/rollback branches, module initialization and resolvers. An
unobserved action is denied; an absent edit workflow must be justified as not
supported, not silently mapped to create. Verify all tenant tables are accounted
for. Add source/drift checks and review the resulting operation map as a security
artefact before connecting it to the server guard.

Broiler/layer isolation must be enforced on shared tables and their parent
scope. A broiler grant cannot authorize layer rows merely because both use the
same table. Overlapping money dependencies also do not mean every writer may
read all those tables. Test hostile queries, joins, CTEs and action mixing.

Current behavior remains fail-closed: staff SQL is denied even if grant rows
contain all four flags. Private grant metadata and this draft do not alter the
farm-admin guard or give platform admins a business SQL path.
`;
const target=resolve(ROOT,'docs/PERMISSION_TABLE_MAP.md');
if(process.argv.includes('--check')) {if(readFileSync(target,'utf8').replaceAll('\r\n','\n')!==out)throw new Error('Permission review worksheet is stale');}
else writeFileSync(target,out);
console.log('Permission worksheet: '+observed.size+'/'+catalogue.entries.length+' screens observed, '+evidence.scopes.length+' action scopes; policy inactive.');
